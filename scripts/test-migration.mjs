test('LFS pointer recognition and size/hash validation do not trust HTTP 200',async()=>{
  const body=Buffer.from('real image fixture');
  const oid=crypto.createHash('sha256').update(body).digest('hex');
  const pointer=parseLfsPointer(`version https://git-lfs.github.com/spec/v1\noid sha256:${oid}\nsize ${body.length}\n`);
  assert.deepEqual(pointer,{oid,size:body.length});
  assert.equal(parseLfsPointer('ordinary text'),null);
  assert.equal(parseLfsPointer(`version https://git-lfs.github.com/spec/v1\noid sha256:${oid}\nsize 999999999999999999999`),null);
  assert.deepEqual(await readVerifiedLfsObject(new Response(body),pointer),body);
  await assert.rejects(readVerifiedLfsObject(new Response('corrupted asset'),pointer),/integrity|size/);
  await assert.rejects(readVerifiedLfsObject(new Response(body,{headers:{'content-length':'1'}}),pointer),/length/);
  await assert.rejects(readVerifiedLfsObject(new Response(body),{...pointer,size:1}),/exceeded/);
});

test('Plugins are parsed as JSON, never executed, and enabled dependencies must exist',()=>{
  const plugins='// generated by RPG Maker\nvar $plugins =\n[{"name":"Core","status":true},{"name":"Unused","status":false}];';
  assert.deepEqual(enabledPluginPaths(plugins),['js/plugins/Core.js']);
  const files=['game/data/System.json','game/js/plugins.js','game/js/main.js','game/js/plugins/Core.js'].map(path=>({path}));
  assert.equal(assertStartupFiles(files,'<script src="js/main.js"></script>','game/index.html',plugins,'game/'),4);
  assert.throws(()=>assertStartupFiles(files.filter(file=>!file.path.includes('Core')),'','game/index.html',plugins,'game/'),/Missing startup/);
  assert.throws(()=>enabledPluginPaths('var $plugins = function(){throw 1}();'),/unsupported/);
  assert.throws(()=>enabledPluginPaths('var $plugins = [{"name":"../other","status":true}];'),/Invalid/);
  assert.throws(()=>assertStartupFiles(files,'<script src="/js/main.js"></script>','game/index.html',plugins,'game/'),/Root-absolute/);
});

test('Full migration preserves same-name games under different owners and deterministic checkpoints',()=>{
  const entries=Array.from({length:1342},(_,i)=>({id:`game-${i}`,title:i%2?'中文':'English',owner:`owner${i}`,name:'game',repo:`https://github.com/owner${i}/game`,status:'indexed'}));
  entries[2].status='hidden';entries[3].status='invalid_structure';
  const plan=planFullMigration(entries,'target');
  assert.equal(plan.length,1342);
  assert.equal(new Set(plan.map(item=>item.forkName.toLowerCase())).size,1342);
  assert.equal(plan.filter(item=>item.skip).length,2);
  assert.deepEqual(planFullMigration([...entries].reverse(),'target'),plan);
  assert.ok(makeForkName('owner','a'.repeat(200)).length<=100);
  assert.equal(migrationFinished({phase:'published'}),true);
  assert.equal(migrationFinished({phase:'preparing'}),false);
  assert.equal(migrationFinished({phase:'paused'}),false);
});

test('Existing automatic fork script retains different owners with the same game name and skips hidden',async()=>{
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'rpg-fork-test-'));
  try{
    const entries=['alice','bob','hidden'].map(owner=>({id:owner,owner,name:'game',repo:`https://github.com/${owner}/game`,status:owner==='hidden'?'hidden':'indexed'}));
    await fs.writeFile(path.join(dir,'list.json'),JSON.stringify(entries));
    const script=path.join(path.dirname(fileURLToPath(import.meta.url)),'fork-listed-repos.mjs');
    const result=await promisify(execFile)(process.execPath,[script],{cwd:dir,env:{...process.env,DRY_RUN:'true',GITHUB_STEP_SUMMARY:'',LIMIT:'0'}});
    assert.match(result.stdout,/alice\/game/);assert.match(result.stdout,/bob\/game/);
    assert.doesNotMatch(result.stdout,/\[dry-run\] hidden\/game/);
    assert.match(result.stdout,/Found 2 unique source repositories/);
  }finally{await fs.rm(dir,{recursive:true,force:true})}
});

test('MZ main.js-only HTML passes startup verification while blank HTML and missing runtime fail',async()=>{
  const html='<script src="js/main.js"></script>';
  let requests=0;
  const request=async url=>{
    requests++;
    return String(url).endsWith('main.js')?new Response('const scriptUrls=["js/rmmz_core.js"];'):
      new Response(html,{headers:{'content-type':'text/html'}});
  };
  assert.deepEqual(await checkPagesEntry('https://example.test/game/index.html',request),{type:'dynamic-main'});
  assert.equal(requests,2);
  await assert.rejects(checkPagesEntry('https://example.test/game/',async()=>new Response('<html>shell</html>',{headers:{'content-type':'text/html'}})),/does not reference/);
  const plugins='var $plugins = [];';
  const files=['data/System.json','js/plugins.js','js/main.js'].map(path=>({path}));
  assert.throws(()=>assertStartupFiles(files,html,'index.html',plugins,'','const scriptUrls = ["js/rmmz_core.js"];'),/Missing startup/);
});

test('Rate-limit cooldown respects Retry-After and primary reset instead of increasing request rate',()=>{
  const now=1794116000000;
  assert.equal(cooldownUntil({},0,now),now+120000);
  assert.equal(cooldownUntil({},2,now),now+480000);
  assert.equal(cooldownUntil({pauseRetryAfter:'600'},0,now),now+600000);
  assert.equal(cooldownUntil({pauseRemaining:'0',pauseResetAt:String(now/1000+3600)},0,now),now+3601000);
  assert.equal(cooldownUntil({},10,now),now+1800000);
});
